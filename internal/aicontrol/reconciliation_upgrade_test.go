package aicontrol

import (
	"context"
	"crypto/sha256"
	"database/sql"
	"encoding/json"
	"errors"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"professional-information-repo/internal/accountstore"
	"sync/atomic"
	"testing"
)

func TestRestrictedReconciliationGenuineBaseUpgrade(t *testing.T) {
	executable := os.Getenv("CAREEROS_RECONCILIATION_BASE_EXECUTABLE")
	if executable == "" {
		t.Skip("requires --legacy-base immutable source fixture")
	}
	path := filepath.Join(t.TempDir(), "private-export.json")
	child := exec.Command(executable, "-test.run=^TestLegacyReconciliationFixtureExport$", "-test.v")
	child.Env = append(os.Environ(), "CAREEROS_RECONCILIATION_EXPORT_PATH="+path)
	out, err := child.CombinedOutput()
	var exited *exec.ExitError
	if !errors.As(err, &exited) || exited.ExitCode() != 73 {
		t.Fatalf("base fixture did not reach durable export: %v %s", err, out)
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var old struct{ Base, DSN, Token, Action, Dispatch, Root, Execution, DispatchBinding, EvidenceBinding string }
	if json.Unmarshal(raw, &old) != nil || old.Base != "ea8b97defb6d0c9593f2bf959bfe007d32ac93c8" {
		t.Fatal("invalid immutable fixture metadata")
	}
	admin, err := sql.Open("pgx", old.DSN)
	if err != nil {
		t.Fatal(err)
	}
	defer admin.Close()
	store, err := accountstore.Open(context.Background(), old.DSN)
	if err != nil {
		t.Fatal(err)
	}
	defer store.Close()
	p, err := authService(t, store).Authenticate(context.Background(), old.Token)
	if err != nil {
		t.Fatal(err)
	}
	gate := NewSyntheticGate()
	gate.Reconcile("fixture", 1)
	cfg := DefaultSyntheticConfig("fixture", gate)
	cfg.Limit = 10000
	cfg.Capacity = 3
	// First migrate using the old key, then rotate while retaining that exact
	// original verifier. These rows were generated by ea8, not the new code.
	h, err := NewSynthetic(context.Background(), old.DSN, cfg)
	if err != nil {
		t.Fatal(err)
	}
	defer h.Close()
	cfg.BindingKeyVersion = "input_v2"
	cfg.BindingKey = sha256.Sum256([]byte("genuine-base-rotation-fixture"))
	cfg.BindingVerificationKeys = map[string][32]byte{"input_v1": h.cfg.BindingKey}
	rotated, err := NewSynthetic(context.Background(), old.DSN, cfg)
	if err != nil {
		t.Fatal(err)
	}
	defer rotated.Close()
	var sends atomic.Int64
	rotated.SetResponder(func(context.Context, string, *http.Request) (*http.Response, error) {
		sends.Add(1)
		return nil, ErrDenied
	})
	session, err := rotated.Open(context.Background(), p, "genuine_base_action", "cv_generation", []byte(`{"synthetic":"root"}`))
	if err != nil || session.ID() != old.Action {
		t.Fatal("base Action identity changed", err)
	}
	resp, err := send(session)
	closeResp(resp)
	if !errors.Is(err, ErrOutputUnavailable) || sends.Load() != 0 {
		t.Fatal("old durable dispatch resent", err)
	}
	var root, execution, dispatch, evidence string
	if err = admin.QueryRow(`SELECT encode(a.binding,'hex'),encode(a.execution_binding,'hex'),encode(d.binding,'hex'),encode(e.binding,'hex') FROM ai_fixture_action a JOIN ai_fixture_dispatch d ON d.namespace=a.namespace AND d.action=a.id JOIN ai_fixture_evidence e ON e.namespace=d.namespace AND e.dispatch=d.id WHERE a.id=$1`, old.Action).Scan(&root, &execution, &dispatch, &evidence); err != nil {
		t.Fatal(err)
	}
	if root != old.Root || execution != old.Execution || dispatch != old.DispatchBinding || evidence != old.EvidenceBinding {
		t.Fatal("migration rewrote inherited binding bytes")
	}
	wrong := cfg
	wrong.BindingVerificationKeys = map[string][32]byte{"input_v1": sha256.Sum256([]byte("changed-verifier"))}
	if bad, err := NewSynthetic(context.Background(), old.DSN, wrong); err == nil {
		bad.Close()
		t.Fatal("changed old key accepted")
	}
	status, err := rotated.Status(context.Background(), p, old.Action)
	if err != nil || len(status.Dispatches) != 1 || status.Dispatches[0].ID != old.Dispatch || status.Dispatches[0].Counted != 60 || status.Dispatches[0].Remote != "possibly_active" {
		t.Fatal(status, err)
	}
}
